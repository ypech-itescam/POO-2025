public class Suma {
    //Suma de los numeros
    public  String suma(int i,int j){
        return "La suma es "+(i+j);
    }
    //Suma de los chars
    public String suma2(char i, char j){
        return "La suma es "+i+j;
    }
    //Suma de los doubles
    public String suma3(double i, double j){
        return "La suma es "+(i+j);
    }
    //Suma de los int y duobles
    public String suma4(double i, int j){
        return "La suma es "+(i+j);
    }

}
